static u32 ms_since(u32 t0) { return (timer_ticks() - t0) * 1000 / 1024; }

void crypto_selftest(void)
{
    u8 pa[32], pb[32], k1[32], k2[32], sm[64], out[64], tag[16];
    unsigned long long outlen;
    u32 t0, x25519_ms, verify_ms, fails = 0;

    t0 = timer_ticks();
    crypto_scalarmult_curve25519_base(pa, dh_a);
    x25519_ms = ms_since(t0);
    crypto_scalarmult_curve25519_base(pb, dh_b);
    crypto_scalarmult_curve25519(k1, dh_a, pb);
    crypto_scalarmult_curve25519(k2, dh_b, pa);
    fails += memcmp(pa, dh_A, 32) != 0;
    fails += memcmp(pb, dh_B, 32) != 0;
    fails += memcmp(k1, dh_K, 32) != 0;
    fails += memcmp(k2, dh_K, 32) != 0;

    memcpy(sm, ed1_sig, 64);                    /* test 1 signs the empty message */
    t0 = timer_ticks();
    fails += crypto_sign_ed25519_open(out, &outlen, sm, 64, ed1_pk) != 0 || outlen != 0;
    verify_ms = ms_since(t0);
    sm[3] ^= 1;
    fails += crypto_sign_ed25519_open(out, &outlen, sm, 64, ed1_pk) == 0;

    crypto_onetimeauth_poly1305(tag, poly_msg, sizeof poly_msg, poly_key);
    fails += memcmp(tag, poly_tag, 16) != 0;

    kprintf("GLOS-CRYPTO kat=%s fails=%u x25519_ms=%u ed25519_verify_ms=%u\n", fails ? "FAIL" : "ok", fails,
            x25519_ms, verify_ms);
}
