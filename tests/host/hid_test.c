/* hid_pad_parse and hid_pad_read (kernel/drv/hidparse.c, docs/gamepad.md J4): the owner's SNES-style pad's own
 * report descriptor and reports (docs/gamepad-j0/: rdesc-081f-e401.bin, guided-081f-e401.txt), and a gamepad
 * descriptor built by hand from the HID 1.11 specification's items: a report ID, signed axes, a hat with a null
 * state, more buttons than a byte. */
#include <stdio.h>
#include <string.h>
#include "hid.h"

static int fails;
#define CHECK(c) do { if (!(c)) { fails++; printf("FAIL %s:%d %s\n", __FILE__, __LINE__, #c); } } while (0)

static const u8 snes[] = {      /* 081f:e401, 98 bytes, as Linux read it */
    0x05, 0x01, 0x09, 0x04, 0xa1, 0x01, 0xa1, 0x02, 0x75, 0x08, 0x95, 0x02, 0x15, 0x00, 0x26, 0xff, 0x00, 0x35, 0x00,
    0x46, 0xff, 0x00, 0x09, 0x30, 0x09, 0x31, 0x81, 0x02, 0x95, 0x03, 0x81, 0x01, 0x75, 0x01, 0x95, 0x04, 0x15, 0x00,
    0x25, 0x01, 0x35, 0x00, 0x45, 0x01, 0x81, 0x01, 0x65, 0x00, 0x75, 0x01, 0x95, 0x0a, 0x25, 0x01, 0x45, 0x01, 0x05,
    0x09, 0x19, 0x01, 0x29, 0x0a, 0x81, 0x02, 0x06, 0x00, 0xff, 0x75, 0x01, 0x95, 0x0a, 0x25, 0x01, 0x45, 0x01, 0x09,
    0x01, 0x81, 0x02, 0xc0, 0xa1, 0x02, 0x75, 0x08, 0x95, 0x07, 0x46, 0xff, 0x00, 0x26, 0xff, 0x00, 0x09, 0x02, 0x91,
    0x02, 0xc0, 0xc0 };

static const u8 pad[] = {       /* a Game Pad: report 1, X Y Z Rz signed -127..127, a 4-bit hat 0-7, 12 buttons */
    0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x85, 0x01, 0x09, 0x30, 0x09, 0x31, 0x09, 0x32, 0x09, 0x35, 0x15, 0x81, 0x25,
    0x7F, 0x75, 0x08, 0x95, 0x04, 0x81, 0x02, 0x09, 0x39, 0x15, 0x00, 0x25, 0x07, 0x75, 0x04, 0x95, 0x01, 0x81, 0x42,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x0C, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x0C, 0x81, 0x02, 0xC0 };

static const u8 ff[] = {        /* a Joystick whose X is 0..FFh written in one byte (25 FF: -1 as a signed byte) */
    0x05, 0x01, 0x09, 0x04, 0xA1, 0x01, 0x09, 0x30, 0x15, 0x00, 0x25, 0xFF, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02, 0xC0 };

static const u8 combo[] = {     /* a combined receiver's mouse: report 2, three buttons, X Y and wheel -127..127 */
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x02, 0x09, 0x01, 0xA1, 0x00, 0x05, 0x09, 0x19, 0x01, 0x29, 0x03,
    0x15, 0x00, 0x25, 0x01, 0x95, 0x03, 0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x03, 0x05, 0x01,
    0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x03, 0x81, 0x06, 0xC0, 0xC0 };

static const u8 mouse[] = {     /* a mouse (Generic Desktop 02h): not a pad */
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x09, 0x30, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x81, 0x06, 0xC0 };

int main(void)
{
    struct hid_pad p;
    struct hid_pad_state s;
    static const u8 rest[] = { 0x7f, 0x7f, 0x80, 0x80, 0x80, 0x0f, 0x00, 0x00 };
    static const u8 y_btn4[] = { 0x7f, 0x7f, 0x80, 0x80, 0x80, 0x8f, 0x00, 0x00 };     /* Y, the left face button */
    static const u8 up_left[] = { 0x00, 0x00, 0x80, 0x80, 0x80, 0x0f, 0x00, 0x00 };
    static const u8 right_start[] = { 0xff, 0x7f, 0x80, 0x80, 0x80, 0x1f, 0x20, 0x00 };   /* X (1) and Start (10) */
    static const u8 r1[] = { 0x01, 0x81, 0x7F, 0x00, 0x00, 0x02, 0x01 }, r2[] = { 0x02, 0, 0, 0, 0, 0, 0 };

    CHECK(sizeof snes == 98);
    CHECK(hid_pad_parse(snes, sizeof snes, &p) == 0);
    CHECK(p.report_id == 0 && p.axes == 0x03 && p.button_mask == 0x3FF && !p.hat.bits);
    CHECK(p.axis[0].bit == 0 && p.axis[0].bits == 8 && p.axis[0].min == 0 && p.axis[0].max == 255);
    CHECK(p.axis[1].bit == 8 && p.button_bit[0] == 44 && p.button_bit[9] == 53);
    CHECK(hid_pad_read(&p, rest, sizeof rest, &s) == 0 && s.axis[0] == 127 && s.axis[1] == 127 && !s.buttons);
    CHECK(s.axis[2] == 128 && s.hat == 8);
    CHECK(hid_pad_read(&p, y_btn4, sizeof y_btn4, &s) == 0 && s.buttons == 0x008);
    CHECK(hid_pad_read(&p, up_left, sizeof up_left, &s) == 0 && s.axis[0] == 0 && s.axis[1] == 0);
    CHECK(hid_pad_read(&p, right_start, sizeof right_start, &s) == 0 && s.axis[0] == 255 && s.buttons == 0x201);

    CHECK(hid_pad_parse(pad, sizeof pad, &p) == 0);
    CHECK(p.report_id == 1 && p.axes == (0x01 | 0x02 | 0x04 | 0x20) && p.button_mask == 0xFFF);
    CHECK(p.axis[0].is_signed && p.axis[0].min == -127 && p.axis[0].max == 127 && p.axis[5].bit == 24);
    CHECK(p.hat.bits == 4 && p.hat.bit == 32 && p.button_bit[0] == 36 && p.button_bit[11] == 47);
    CHECK(hid_pad_read(&p, r1, sizeof r1, &s) == 0);
    CHECK(s.axis[0] == 0 && s.axis[1] == 255 && s.axis[2] == 128 && s.axis[5] == 128 && s.axis[3] == 128);
    CHECK(s.hat == 2 && s.buttons == 0x010);
    CHECK(hid_pad_read(&p, r2, sizeof r2, &s) == -1);                 /* another report's */

    CHECK(hid_pad_parse(ff, sizeof ff, &p) == 0 && p.axis[0].max == 255 && !p.axis[0].is_signed);
    CHECK(hid_pad_parse(mouse, sizeof mouse, &p) == -1);

    {   /* mice: the combined receiver's as the bench's touchpad behaved (report ID, then buttons, X, Y) */
        static const u8 m1[] = { 0x02, 0x01, 0x05, 0xFD, 0x00 }, m2[] = { 0x02, 0x02, 0x00, 0x00, 0xFF };
        static const u8 m3[] = { 0x01, 0x01, 0x05, 0x05, 0x00 };
        int dx, dy, wh;
        u16 b;
        CHECK(hid_parse(combo, sizeof combo, HID_WANT_MOUSE, &p) == 0);
        CHECK(p.report_id == 2 && p.axes == 3 && p.button_mask == 7 && p.wheel.bits == 8);
        CHECK(p.button_bit[0] == 0 && p.axis[0].bit == 8 && p.axis[1].bit == 16 && p.wheel.bit == 24);
        CHECK(hid_mouse_read(&p, m1, sizeof m1, &dx, &dy, &wh, &b) == 0 && dx == 5 && dy == -3 && !wh && b == 1);
        CHECK(hid_mouse_read(&p, m2, sizeof m2, &dx, &dy, &wh, &b) == 0 && !dx && !dy && wh == -1 && b == 2);
        CHECK(hid_mouse_read(&p, m3, sizeof m3, &dx, &dy, &wh, &b) == -1);     /* the keyboard's report */
        CHECK(hid_parse(mouse, sizeof mouse, HID_WANT_MOUSE, &p) == 0 && p.report_id == 0 && p.axes == 1);
        CHECK(hid_parse(pad, sizeof pad, HID_WANT_MOUSE, &p) == -1);   /* a pad isn't a mouse */
    }

    printf("hid_test: %d failures\n", fails);
    return fails != 0;
}
