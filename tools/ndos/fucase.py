#!/usr/bin/env python3
"""fucase.py COUNTRY.SYS OUT.c: MS-DOS's file-name upper-case tables (INT 21h 6504h; COUNTRY.SYS's "FUCASE"
tables, RBIL tables 02619-02622) for the code pages GLOS has, as C data for kernel/ndos/names.c.

The owner's choice (2026-11-22): GLOS keeps MS-DOS 7.1's own tables, made from the owner's Windows 98 SE's
COUNTRY.SYS (MSDOS_DIR), because they follow no rule (437's e acute is E though 437 has E acute). Per code page
the most common of its countries' tables, which is its default country's (437 and 850: 001; 737: 030; 852: the
Central European group; 866: 007); the others (437's for Belgium, Switzerland, Sweden and Finland make e acute
E acute; the Netherlands' more) wait for a region setting to choose them. Said on stderr where they differ."""
import struct
import sys
from collections import Counter

PAGES = (437, 737, 850, 852, 866)


def tables(path):
    d = open(path, "rb").read()
    if d[0] != 0xFF or d[1:8] != b"COUNTRY":
        sys.exit("fucase.py: %s is no COUNTRY.SYS" % path)
    first = struct.unpack_from("<I", d, 0x13)[0]
    n = struct.unpack_from("<H", d, first)[0]
    off, found = first + 2, {}
    for _ in range(n):
        ln, country, cp, _a, _b, sub = struct.unpack_from("<HHHHHI", d, off)
        off += ln + 2
        m = struct.unpack_from("<H", d, sub)[0]
        so = sub + 2
        for _ in range(m):
            sl, sid, data = struct.unpack_from("<HHI", d, so)
            so += sl + 2
            if sid == 4 and d[data] == 0xFF:  # (often the "UCASE" table itself, shared where the two agree)
                length = struct.unpack_from("<H", d, data + 8)[0]
                found.setdefault(cp, {})[country] = bytes(d[data + 10:data + 10 + length])
    return found


def main():
    found = tables(sys.argv[1])
    out = ["/* Generated by tools/ndos/fucase.py from MS-DOS 7.1's COUNTRY.SYS (the owner's Windows 98 SE): its file-name",
           "   upper-case tables (INT 21h 6504h), bytes 80h-FFh, for the code pages GLOS has. Kept as MS-DOS has them by",
           "   the owner's choice (2026-11-22): they follow no rule. Not to be edited by hand. */",
           '#include "names.h"', "",
           "const struct dos_fucase dos_fucase_tables[] = {"]
    for cp in PAGES:
        if cp not in found:
            sys.exit("fucase.py: no table for code page %d" % cp)
        common = Counter(found[cp].values()).most_common()
        if len(common) > 1:
            print("fucase.py: code page %d: %d different tables among its countries; the most common kept"
                  % (cp, len(common)), file=sys.stderr)
        t = common[0][0]
        if len(t) != 128:
            sys.exit("fucase.py: code page %d: a table of %d bytes" % (cp, len(t)))
        out.append("    { %d, {" % cp)
        for i in range(0, 128, 16):
            out.append("        " + ", ".join("0x%02X" % b for b in t[i:i + 16]) + ",")
        out.append("    } },")
    out += ["    { 0, { 0 } }", "};", ""]
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
